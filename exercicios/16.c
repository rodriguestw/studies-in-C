#include <stdio.h>
#include <locale.h>

int main (){
    setlocale(LC_ALL, "Portuguese");

    float n1, n2, media;

    printf("Digite sua nota 1:\n");
    scanf("%f", &n1);

    printf("Digite sua nota 2:\n");
    scanf("%f", &n2);

    media = (n1 + n2) / 2;
    

    if (media >= 7){
        printf("Sua nota e %.2f\n", media);
        printf("Aprovado!");
    } else if (media >= 5 && media < 7){
        printf("Sua nota e %.2f\n", media);
        printf("Recuperação!");
    } else {
        printf("Sua nota e %.2f\n", media);
        printf("Reprovado!");
    }
}


